const sourcePhrases = Object.keys(phraseTranslations);

export const translations = {
  en: Object.fromEntries(sourcePhrases.map((phrase) => [phrase, phrase])),
  fr: Object.fromEntries(sourcePhrases.map((phrase) => [phrase, phraseTranslations[phrase][0]])),
  rw: Object.fromEntries(sourcePhrases.map((phrase) => [phrase, phraseTranslations[phrase][1]]))
};

function interpolate(template, values) {
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, key) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : placeholder
  );
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function matchTemplate(text, template) {
  const placeholders = [];
  const expression = template
    .split(/(\{[A-Za-z0-9_]+\})/g)
    .map((part) => {
      const placeholder = part.match(/^\{([A-Za-z0-9_]+)\}$/);
      if (placeholder) {
        placeholders.push(placeholder[1]);
        return "(.+?)";
      }
      return escapeRegExp(part);
    })
    .join("");

  if (!placeholders.length) return null;
  const match = text.match(new RegExp(`^${expression}$`));
  if (!match) return null;

  return placeholders.reduce((translated, key, index) => {
    return translated.replace(`{${key}}`, match[index + 1]);
  }, template);
}

export function translateText(text, language = "en", values = {}) {
  if (typeof text !== "string") return text;
  const locale = String(language || "en").toLowerCase().split(/[-_]/)[0];
  const dictionary = translations[locale] || translations.en;
  const phrase = dictionary[text] || text;

  if (Object.keys(values).length) return interpolate(phrase, values);
  if (phrase !== text || locale === "en") return phrase;

  for (const [source, translated] of Object.entries(dictionary)) {
    const result = matchTemplate(text, source);
    if (result !== null) return matchTemplateTranslation(text, source, translated);
  }
  return text;
}

function matchTemplateTranslation(text, source, translated) {
  const names = [];
  const expression = source
    .split(/(\{[A-Za-z0-9_]+\})/g)
    .map((part) => {
      const placeholder = part.match(/^\{([A-Za-z0-9_]+)\}$/);
      if (placeholder) {
        names.push(placeholder[1]);
        return "(.+?)";
      }
      return escapeRegExp(part);
    })
    .join("");
  const match = text.match(new RegExp(`^${expression}$`));
  if (!match) return text;
  return names.reduce((result, name, index) => result.replace(`{${name}}`, match[index + 1]), translated);
}
